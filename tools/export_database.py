"""Export the career database to readable files in Database/export/.

Usage (from the project folder):
    python tools/export_database.py

Creates:
    Database/export/schema.sql       CREATE TABLE / CREATE INDEX statements of every table
    Database/export/careers.csv      the 88 careers with all their fields
    Database/export/interests.csv    the interests and the careers linked to each
"""
import csv
import os
import sqlite3

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.environ.get("CAREER_DB_PATH", os.path.join(BASE, "Database", "career_counseling.db"))
OUT = os.path.join(BASE, "Database", "export")


def main():
    os.makedirs(OUT, exist_ok=True)
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row

    rows = con.execute(
        "SELECT type, name, sql FROM sqlite_master "
        "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type DESC, name"
    ).fetchall()
    with open(os.path.join(OUT, "schema.sql"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Schema of Database/career_counseling.db (SQLite 3)\n")
        f.write("-- Generated by tools/export_database.py\n\n")
        for r in rows:
            f.write(r["sql"].strip() + ";\n\n")

    careers = con.execute("SELECT * FROM Careers ORDER BY id").fetchall()
    with open(os.path.join(OUT, "careers.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(careers[0].keys())
        for r in careers:
            w.writerow(list(r))

    interests = con.execute(
        "SELECT i.id, i.interest_name, GROUP_CONCAT(c.career_name, '; ') AS careers "
        "FROM Interests i LEFT JOIN CareerInterests ci ON ci.interest_id = i.id "
        "LEFT JOIN Careers c ON c.id = ci.career_id GROUP BY i.id ORDER BY i.id"
    ).fetchall()
    with open(os.path.join(OUT, "interests.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "interest_name", "linked_careers"])
        for r in interests:
            w.writerow(list(r))
    con.close()
    print(f"Exported {len(careers)} careers, {len(interests)} interests and the schema to {OUT}")


if __name__ == "__main__":
    main()
